fails = []


def check(cond, msg):
    print(('  ok  ' if cond else '  FAIL ') + msg)
    if not cond:
        fails.append(msg)


def open_page(browser, query='fresh', width=420, height=860):
    page = browser.new_page(viewport={'width': width, 'height': height}, device_scale_factor=2)
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: errors.append(m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
    page.goto(f'{BASE}?{query}')
    page.wait_for_function('window.__mageLoaded === true')
    page.evaluate('localStorage.clear()') if 'fresh' in query else None
    return page, errors


def turn(page):
    page.evaluate('window.__fakeST.turn()'); page.wait_for_timeout(120)


def swipe(page):
    page.evaluate('window.__fakeST.swipe()'); page.wait_for_timeout(120)


def dele(page):
    page.evaluate('window.__fakeST.deleteLast()'); page.wait_for_timeout(120)


def prompt(page):
    return page.evaluate('window.__fakeST.prompt') or ''


def open_win(page):
    if page.evaluate("!document.getElementById('mage_win') || document.getElementById('mage_win').hidden"):
        page.evaluate("document.querySelector('#mage_wand').click()")


def cast(page, spell='polymorph', form=None, duration=None, target=None, more=None):
    open_win(page)
    page.click('[data-mage-view="cast"]')
    if target:
        page.select_option('[data-f="target"]', target)
    if page.query_selector('.mage-lgrid'):
        page.click(f'[data-mage-pick="{spell}"]')
    else:
        page.select_option('[data-f="spell"]', spell)
    if form:
        page.select_option('[data-f="formSel"]', form)
    if duration is not None:
        page.click(f'[data-mage-dur="{duration}"]')
    if more:
        if page.get_attribute('[data-mage-details]', 'aria-expanded') != 'true':
            page.click('[data-mage-details]')
        more(page)
    page.click('[data-mage-cast]')


def mine(pg):
    pg.select_option('[data-f="srcKind"]', 'me')


def rules_on(page, on=True):
    page.evaluate(f"""(() => {{ const el = document.querySelector('#mage_settings [data-mage-p="rules"]'); el.checked = {'true' if on else 'false'}; el.dispatchEvent(new Event('change', {{ bubbles: true }})); }})()""")
    page.wait_for_timeout(80)


def mana(page):
    return page.inner_text('#mage_bar .mage-mana').replace('◆', '').strip()


def set_pref(page, key, value):
    """Change a setting in the extension panel (checkbox: True/False, else a value)."""
    if isinstance(value, bool):
        page.evaluate(f"""(() => {{ const el = document.querySelector('#mage_settings [data-mage-p="{key}"]'); el.checked = {'true' if value else 'false'}; el.dispatchEvent(new Event('change', {{ bubbles: true }})); }})()""")
    else:
        page.evaluate(f"""(() => {{ const el = document.querySelector('#mage_settings [data-mage-p="{key}"]'); el.value = '{value}'; el.dispatchEvent(new Event('change', {{ bubbles: true }})); }})()""")
    page.wait_for_timeout(80)


